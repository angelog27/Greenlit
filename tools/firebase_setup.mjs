// Reads the Firebase web config from .env (repo root first, then Frontend/.env) and writes:
//   Frontend/firebase-config.js  window.FIREBASE_CONFIG for the page (git-ignored)
//   .firebaserc                   default project for the Firebase CLI
// The web config (apiKey, authDomain, projectId, ...) identifies the project and is public by design; it is
// not an admin credential. Prints only which keys were found, never their values.
// Accepts `apiKey=...` or `FIREBASE_API_KEY=...` style names (also "KEY: value" and quoted values).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const KEYS = ["apiKey", "authDomain", "projectId", "storageBucket", "messagingSenderId", "appId", "measurementId"];
const alias = (k) => {
  const plain = k.replace(/^FIREBASE_/i, "").toLowerCase().replace(/_/g, "");
  return KEYS.find((x) => x.toLowerCase() === plain);
};

const cfg = {};
for (const f of [".env", "Frontend/.env"]) {
  const p = path.join(ROOT, f);
  if (!fs.existsSync(p)) continue;
  for (const line of fs.readFileSync(p, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*[:=]\s*["']?([^"',\s]+)["']?\s*,?\s*$/);
    const k = m && alias(m[1]);
    if (k && !cfg[k]) cfg[k] = m[2];
  }
}
const missing = ["apiKey", "authDomain", "projectId", "appId"].filter((k) => !cfg[k]);
if (missing.length) {
  console.error("Missing Firebase web config keys in .env: " + missing.join(", "));
  process.exit(1);
}
const ordered = Object.fromEntries(KEYS.filter((k) => cfg[k]).map((k) => [k, cfg[k]]));
fs.writeFileSync(path.join(ROOT, "Frontend", "firebase-config.js"),
  "// Generated by tools/firebase_setup.mjs from .env. Public web config, not a secret.\nwindow.FIREBASE_CONFIG = " + JSON.stringify(ordered, null, 2) + ";\n");
fs.writeFileSync(path.join(ROOT, ".firebaserc"), JSON.stringify({ projects: { default: cfg.projectId } }, null, 2) + "\n");
console.log("wrote Frontend/firebase-config.js and .firebaserc with: " + Object.keys(ordered).join(", "));
